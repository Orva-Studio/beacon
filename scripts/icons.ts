// Copies the editor's icons out of Phosphor's package (MIT) into ui/src/controls/icon-paths.ts.
//   npm pack @phosphor-icons/core@2.1.1 && tar xzf phosphor-icons-core-2.1.1.tgz
//   bun scripts/icons.ts <extracted package dir>
// Add a name to NAMES and run it again to use another icon (https://phosphoricons.com).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const NAMES = [
  "star", "film-strip", "chat-centered-text", "magic-wand", "waveform", "microphone",
  "arrow-counter-clockwise", "arrow-clockwise", "scissors", "copy", "clipboard-text", "split-horizontal", "camera",
  "minus", "plus", "arrows-out-line-horizontal",
  "skip-back", "skip-forward", "caret-left", "caret-right", "play", "pause", "arrow-line-left", "arrow-line-right",
  "speaker-high", "speaker-slash", "lock-simple", "lock-simple-open", "eye", "eye-slash", "magnet",
  "trash", "x", "sparkle", "monitor-play", "video-camera", "image", "music-note", "sort-ascending", "sort-descending",
  "caret-down", "dots-three", "eyedropper", "gauge", "link-simple-horizontal", "magnifying-glass", "squares-four", "list", "check", "closed-captioning",
  "align-top", "align-center-vertical", "align-bottom", "align-left", "align-center-horizontal", "align-right", "floppy-disk",
];

/** Drawn for Beacon on the same grid, where Phosphor has no match: regular (a 16-unit outline), then fill. */
const CUSTOM: Record<string, [string, string]> = {
  // A macOS-style arrow pointer (Phosphor's cursor reads as a navigation arrow).
  pointer: ["M68,18L192,142L136,146L176,218L136,238L96,166L68,208ZM84,155.2L97.2,135.3L142.5,216.8L153.9,211.2L109.8,131.8L155.9,128.5L84,56.6Z", "M68,18L192,142L136,146L176,218L136,238L96,166L68,208Z"],
};

const dir = process.argv[2];
if (!dir) throw new Error("usage: bun scripts/icons.ts <@phosphor-icons/core package dir>");
const path = (weight: string, file: string) => {
  const svg = readFileSync(join(dir, "assets", weight, file), "utf8");
  const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (d.length !== 1) throw new Error(`${weight}/${file}: expected one path, found ${d.length}`);
  return d[0]!;
};
const version = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).version as string;
const lines = [
  ...NAMES.map((n) => `  "${n}": [${JSON.stringify(path("regular", `${n}.svg`))}, ${JSON.stringify(path("fill", `${n}-fill.svg`))}],`),
  ...Object.entries(CUSTOM).map(([n, [regular, fill]]) => `  "${n}": [${JSON.stringify(regular)}, ${JSON.stringify(fill)}],`),
];
writeFileSync(
  join(import.meta.dir, "../packages/ui/src/controls/icon-paths.ts"),
  `// Generated by scripts/icons.ts from @phosphor-icons/core ${version} (MIT, https://phosphoricons.com), plus CUSTOM; don't edit.\n` +
    `/** Each icon's path on a 256×256 grid: regular weight, then fill. */\n` +
    `export const ICON_PATHS = {\n${lines.join("\n")}\n} as const;\n`,
);
console.log(`${NAMES.length} icons`);
